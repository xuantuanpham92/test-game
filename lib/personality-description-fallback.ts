function countStructuredSections(description: string) {
  return [...description.matchAll(/【([^】]+)】/g)].length;
}

export function getDisplayLongDescription(
  typeKey: string | null | undefined,
  databaseDescription: string | null | undefined
) {
  const description = databaseDescription?.trim() || "";
  if (countStructuredSections(description) >= MIN_STRUCTURED_SECTION_COUNT) {
    return description;
  }

  if (typeKey && CANONICAL_LONG_DESCRIPTIONS[typeKey]) {
    return CANONICAL_LONG_DESCRIPTIONS[typeKey];
  }

  return description;
}
